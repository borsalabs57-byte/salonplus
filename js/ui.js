// ── UI Utilities ──
const UI = {
  // Toast notifications
  showToast(message, type = 'default') {
    const container = document.getElementById('toast-container');
    if (!container) return;

    const iconMap = {
      success: Icons.checkCircle,
      error: Icons.alertCircle,
      warning: Icons.alertCircle,
      default: Icons.bell
    };

    const toast = document.createElement('div');
    toast.className = `toast toast-${type}`;
    toast.innerHTML = `${iconMap[type] || iconMap.default}<span>${message}</span>`;
    container.appendChild(toast);

    setTimeout(() => toast.remove(), 3200);
  },

  // Show modal
  showModal(title, contentHtml, options = {}) {
    const backdrop = document.createElement('div');
    backdrop.className = `modal-backdrop ${options.center ? 'modal-center' : ''}`;
    backdrop.id = 'active-modal';

    const closeModal = () => backdrop.remove();
    backdrop.addEventListener('click', (e) => {
      if (e.target === backdrop) closeModal();
    });

    backdrop.innerHTML = `
      <div class="modal">
        <div class="modal-handle"></div>
        ${title ? `<div class="modal-title">${title}</div>` : ''}
        <div class="modal-body">${contentHtml}</div>
      </div>
    `;

    document.body.appendChild(backdrop);
    return { close: closeModal, element: backdrop };
  },

  closeModal() {
    document.getElementById('active-modal')?.remove();
  },

  // Empty state
  renderEmptyState(icon, title, text, ctaText = '', ctaAction = '') {
    return `
      <div class="empty-state">
        <div class="empty-state-icon">${icon}</div>
        <div class="empty-state-title">${title}</div>
        <div class="empty-state-text">${text}</div>
        ${ctaText ? `<button class="btn btn-primary" onclick="${ctaAction}">${ctaText}</button>` : ''}
      </div>
    `;
  },

  // Error state
  renderErrorState(message) {
    return `
      <div class="error-state">
        <div class="error-state-title">${Icons.alertCircle} Something went wrong</div>
        <p class="text-sm text-secondary mt-2">${message}</p>
        <button class="btn btn-outline btn-sm mt-4" onclick="location.reload()">Retry</button>
      </div>
    `;
  },

  // Loading skeleton
  renderSkeleton(count = 3) {
    return Array(count).fill('').map(() => `
      <div class="skeleton skeleton-card"></div>
    `).join('');
  },

  // Simulate loading
  async simulateLoad(ms = 400) {
    return new Promise(r => setTimeout(r, ms));
  },

  // Avatar
  renderAvatar(name, size = '') {
    const cls = size ? `avatar avatar-${size}` : 'avatar';
    return `<div class="${cls}">${Utils.getInitials(name)}</div>`;
  },

  // Badge
  renderBadge(text, type = 'neutral') {
    return `<span class="badge badge-${type}">${text}</span>`;
  },

  // Status badge
  renderStatusBadge(status) {
    return `<span class="badge ${Utils.getStatusBadgeClass(status)}"><span class="status-dot status-dot-${status.toLowerCase().replace('-', '')}"></span>${status}</span>`;
  }
};
